_WINDOWS_DRIVE_RE = re.compile(r"^[A-Za-z]:")


def resolve_repository_relative_path(repo_root: Path, relative_path: Any, *, binding_name: str = "") -> Path:
    """The SOLE path through which any repository-file dependency
    binding is ever resolved for hashing (path-traversal/absolute-
    substitution/symlink-escape repair). Strictly validates
    ``relative_path`` as a canonical, repository-relative,
    forward-slash-only string with no absolute (POSIX or Windows
    drive/UNC), backslash, ``..``, ``.``, or empty-component syntax --
    entirely BEFORE any filesystem access -- then resolves it against
    the fully-resolved (symlink-chased) repository root and requires
    the fully-resolved (symlink-chased) target to remain physically
    contained beneath that root and be an existing regular file.

    A ``repo_root`` itself reached through a symlink is accepted --
    containment is evaluated against ITS resolved physical path, not
    its symlink path -- so a repository checked out through a symlinked
    directory still validates correctly.

    Never uses only a string-prefix check (unsafe for paths like
    ``/repo-root-other/file``): containment is decided by
    ``Path.relative_to`` against two independently-resolved physical
    paths. Ordinary path/filesystem failures are translated to
    ``DfpPhase1bChunkBenchmarkIdentityError`` (with the original
    exception preserved as ``__cause__``); ``KeyboardInterrupt``,
    ``SystemExit``, and ``MemoryError`` are never caught here."""
    label = f"dependency_bindings.{binding_name}.relative_path" if binding_name else "relative_path"

    if type(relative_path) is not str or len(relative_path) == 0:
        raise DfpPhase1bChunkBenchmarkIdentityError(f"{label} must be a nonempty string, observed {relative_path!r}")
    if "\x00" in relative_path:
        raise DfpPhase1bChunkBenchmarkIdentityError(f"{label} must not contain a NUL byte")
    if relative_path != relative_path.strip():
        raise DfpPhase1bChunkBenchmarkIdentityError(f"{label} must not have leading/trailing whitespace, observed {relative_path!r}")
    if "\\" in relative_path:
        raise DfpPhase1bChunkBenchmarkIdentityError(f"{label} must use forward slashes only (no backslashes), observed {relative_path!r}")
    if relative_path.startswith("/"):
        raise DfpPhase1bChunkBenchmarkIdentityError(f"{label} must be repository-relative, not POSIX-absolute: {relative_path!r}")
    if _WINDOWS_DRIVE_RE.match(relative_path):
        raise DfpPhase1bChunkBenchmarkIdentityError(f"{label} must not be a Windows drive path: {relative_path!r}")

    parts = relative_path.split("/")
    for part in parts:
        if part == "":
            raise DfpPhase1bChunkBenchmarkIdentityError(
                f"{label} must not contain an empty path component (doubled separator or leading/trailing slash): {relative_path!r}"
            )
        if part == ".":
            raise DfpPhase1bChunkBenchmarkIdentityError(f"{label} must not contain a '.' component: {relative_path!r}")
        if part == "..":
            raise DfpPhase1bChunkBenchmarkIdentityError(f"{label} must not contain a '..' component: {relative_path!r}")

    try:
        resolved_root = Path(repo_root).resolve(strict=True)
    except OSError as exc:
        raise DfpPhase1bChunkBenchmarkIdentityError(f"cannot resolve repository root {repo_root}: {exc}") from exc

    candidate = resolved_root.joinpath(*parts)
    try:
        resolved_target = candidate.resolve(strict=True)
    except OSError as exc:
        raise DfpPhase1bChunkBenchmarkIdentityError(f"{label} does not resolve to an existing path: {relative_path!r} ({exc})") from exc

    try:
        resolved_target.relative_to(resolved_root)
    except ValueError as exc:
        raise DfpPhase1bChunkBenchmarkIdentityError(
            f"{label} resolves outside the repository root -- refusing (target={resolved_target}, root={resolved_root})"
        ) from exc

    if not resolved_target.is_file():
        raise DfpPhase1bChunkBenchmarkIdentityError(f"{label} does not resolve to a regular file: {resolved_target}")

    return resolved_target

def _walk_closed(node: Any, prefix: str) -> None:
    if not isinstance(node, dict):
        return
    expected = SECTION_TREE.get(prefix)
    if expected is not None:
        actual = frozenset(node.keys())
        if actual != expected:
            missing = expected - actual
            unknown = actual - expected
            raise DfpPhase1bChunkBenchmarkIdentityError(
                f"section {prefix!r} has the wrong key set -- missing={sorted(missing)} unknown={sorted(unknown)}"
            )
    for key, value in node.items():
        if isinstance(value, dict):
            child_prefix = f"{prefix}.{key}" if prefix else key
            _walk_closed(value, child_prefix)


def _exact_value_matches(actual: Any, expected: Any) -> bool:
    """Strict equality: rejects bool-as-int and int-as-float (Python's
    ``True == 1`` and ``1 == 1.0`` would otherwise silently pass)."""
    if type(actual) is not type(expected):
        return False
    if isinstance(expected, list):
        if len(actual) != len(expected):
            return False
        return all(_exact_value_matches(a, e) for a, e in zip(actual, expected))
    return actual == expected


def _walk_canonical_values(node: Any, prefix: str, canonical: Mapping[str, Any]) -> None:
    """For every leaf NOT itself a dict (scalars and lists-of-scalars),
    if its dotted path is a hash/path-relational field it is skipped
    here (verified separately, relationally); otherwise it MUST appear
    in ``canonical`` with an exact, strictly-typed match. A leaf dotted
    path present in the document but absent from ``canonical`` (and not
    a known relational field) is itself a validation failure -- this
    is what prevents a newly-added authoritative leaf from silently
    escaping exact-value pinning."""
    if isinstance(node, dict):
        for key, value in node.items():
            child_prefix = f"{prefix}.{key}" if prefix else key
            if key in _RELATIONAL_LEAF_KEYS:
                continue
            if isinstance(value, dict):
                _walk_canonical_values(value, child_prefix, canonical)
            elif isinstance(value, list) and value and isinstance(value[0], dict):
                if child_prefix not in canonical:
                    raise DfpPhase1bChunkBenchmarkIdentityError(f"authoritative leaf {child_prefix!r} is not exact-value pinned")
                if not _exact_value_matches(value, canonical[child_prefix]):
                    raise DfpPhase1bChunkBenchmarkIdentityError(
                        f"E17 {child_prefix} must be exactly {canonical[child_prefix]!r}, observed {value!r}"
                    )
            else:
                if child_prefix not in canonical:
                    raise DfpPhase1bChunkBenchmarkIdentityError(f"authoritative leaf {child_prefix!r} is not exact-value pinned")
                if not _exact_value_matches(value, canonical[child_prefix]):
                    raise DfpPhase1bChunkBenchmarkIdentityError(
                        f"E17 {child_prefix} must be exactly {canonical[child_prefix]!r}, observed {value!r}"
                    )


_RELATIONAL_LEAF_KEYS: frozenset[str] = frozenset(
    [
        "sha256", "relative_path", "sha256_pinned_here", "sha256_verification",
        "untouched_by_this_identity", "relative_path_is_symbolic_not_repository_relative",
        "relative_path_note", "self_reference_note",
    ]
)


def _sha256_of(path: Path) -> str:
    try:
        raw = path.read_bytes()
    except OSError as exc:
        raise DfpPhase1bChunkBenchmarkIdentityError(f"cannot read bound file {path}: {exc}") from exc
    return hashlib.sha256(raw).hexdigest()


def load_identity(
    path: Path | None = None, *, repo_root: Path | None = None,
    calibration_artifact_path: Path | None = None, workload_bundle_dir: Path | None = None,
) -> dict[str, Any]:
    """Load, closed-schema-validate, exhaustively exact-value-validate,
    and relationally re-verify E17 (including the benchmark's own
    executable code: identity loader, runner, CLI, launcher).

    ``calibration_artifact_path``/``workload_bundle_dir`` resolve the
    two symbolic (scratch-output, non-repository) bindings -- callers
    that only need the frozen TOML content (e.g. ``--help``, CLI
    argument parsing) may omit them; callers that need full relational
    verification (``verify-protocol``, ``preflight``, ``run-trial``)
    must supply both."""
    root = Path(repo_root) if repo_root is not None else repository_root()
    identity_path = Path(path) if path is not None else (root / IDENTITY_RELATIVE_PATH)
    try:
        with open(identity_path, "rb") as handle:
            document = tomllib.load(handle)
    except OSError as exc:
        raise DfpPhase1bChunkBenchmarkIdentityError(f"cannot read E17 identity {identity_path}: {exc}") from exc
    except tomllib.TOMLDecodeError as exc:
        raise DfpPhase1bChunkBenchmarkIdentityError(f"E17 identity {identity_path} is not valid TOML: {exc}") from exc

    top_keys = frozenset(document.keys())
    if top_keys != TOP_KEYS:
        raise DfpPhase1bChunkBenchmarkIdentityError(
            f"E17 identity has the wrong top-level key set -- missing={sorted(TOP_KEYS - top_keys)} "
            f"unknown={sorted(top_keys - TOP_KEYS)}"
        )
    _walk_closed(document, "")

    if document["format_version"] != FORMAT_VERSION:
        raise DfpPhase1bChunkBenchmarkIdentityError(
            f"E17 identity format_version must be {FORMAT_VERSION!r}, observed {document['format_version']!r}"
        )

    # Exhaustive exact-value validation: every non-hash/non-path leaf
    # anywhere in the document must match CANONICAL_VALUES exactly.
    _walk_canonical_values(document, "", CANONICAL_VALUES)

    # Relational hash re-verification of every repository-relative
    # scientific dependency AND the benchmark's own executable code.
    resolved_paths: dict[str, Path | None] = {
        "calibration_artifact": Path(calibration_artifact_path) if calibration_artifact_path is not None else None,
    }
    if workload_bundle_dir is not None:
        resolved_paths["workload_selected_window_csv"] = Path(workload_bundle_dir) / "selected_window_workload.csv"
        resolved_paths["workload_statistics_json"] = Path(workload_bundle_dir) / "workload_statistics.json"
    else:
        resolved_paths["workload_selected_window_csv"] = None
        resolved_paths["workload_statistics_json"] = None

    # Canonical dependency-path authority: every repository-file
    # binding's relative_path must equal its OWN pinned canonical
    # value exactly, checked entirely in-memory BEFORE any filesystem
    # access -- this is what rejects swapping two otherwise-valid
    # paths, or substituting a different in-repository file (even one
    # whose hash is then recomputed to match), regardless of what the
    # recomputed hash says.
    for name in _REPOSITORY_FILE_BINDING_NAMES:
        binding = document["dependency_bindings"][name]
        observed_relative_path = binding["relative_path"]
        canonical_relative_path = CANONICAL_DEPENDENCY_RELATIVE_PATHS[name]
        if observed_relative_path != canonical_relative_path:
            raise DfpPhase1bChunkBenchmarkIdentityError(
                f"E17 dependency_bindings.{name}.relative_path must be exactly {canonical_relative_path!r}, "
                f"observed {observed_relative_path!r}"
            )

    for name in _REPO_RELATIVE_HASHED_BINDING_NAMES:
        binding = document["dependency_bindings"][name]
        target = resolve_repository_relative_path(root, binding["relative_path"], binding_name=name)
        actual = _sha256_of(target)
        if actual != binding["sha256"]:
            raise DfpPhase1bChunkBenchmarkIdentityError(
                f"E17 dependency_bindings.{name} SHA-256 mismatch for {target} -- pinned {binding['sha256']}, observed {actual}"
            )
    for name in _CODE_BINDING_NAMES:
        binding = document["dependency_bindings"][name]
        target = resolve_repository_relative_path(root, binding["relative_path"], binding_name=name)
        actual = _sha256_of(target)
        if actual != binding["sha256"]:
            raise DfpPhase1bChunkBenchmarkIdentityError(
                f"E17 dependency_bindings.{name} (benchmark code) SHA-256 mismatch for {target} -- "
                f"pinned {binding['sha256']}, observed {actual} -- the executed benchmark code has drifted from what this identity binds"
            )
    for name in ("calibration_artifact", "workload_selected_window_csv", "workload_statistics_json"):
        binding = document["dependency_bindings"][name]
        target = resolved_paths.get(name)
        if target is None:
            continue  # caller did not request relational verification for this binding
        actual = _sha256_of(target)
        if actual != binding["sha256"]:
            raise DfpPhase1bChunkBenchmarkIdentityError(
                f"E17 dependency_bindings.{name} SHA-256 mismatch for {target} -- pinned {binding['sha256']}, observed {actual}"
            )

    return document


# ---------------------------------------------------------------------
# Memory-guard contract: the SOLE source of truth for the operational
# abort guard. Derived exclusively from an already-verified E17
# document -- never a Python default, never overridable by CLI flag or
# environment variable (Finding 2 repair).
# ---------------------------------------------------------------------


@dataclass(frozen=True)
class MemoryGuardContract:
    allocated_host_gib: float
    allocated_gpu_gib: float
    host_abort_fraction: float
    gpu_abort_fraction: float

    def host_limit_bytes(self) -> float:
        return self.allocated_host_gib * (1024**3) * self.host_abort_fraction

    def gpu_limit_bytes(self) -> float:
        return self.allocated_gpu_gib * (1024**3) * self.gpu_abort_fraction


def memory_guard_contract_from_identity(document: Mapping[str, Any]) -> MemoryGuardContract:
    """Extract the four frozen safety-guard values from an
    already-loaded (closed-schema, exact-value-validated) E17
    document. This is the ONLY place a ``MemoryGuardContract`` may be
    constructed from parsed TOML data -- callers must never hand-build
    one from a literal or a hardcoded default."""
    guard = document["measurement"]["safety_guard"]
    if guard["comparison_operator"] != "strictly_greater_than":
        raise DfpPhase1bChunkBenchmarkIdentityError(
            f"E17 measurement.safety_guard.comparison_operator must be 'strictly_greater_than', observed {guard['comparison_operator']!r}"
        )
    return MemoryGuardContract(
        allocated_host_gib=float(guard["allocated_host_memory_gib"]),
        allocated_gpu_gib=float(guard["allocated_gpu_memory_gib"]),
        host_abort_fraction=float(guard["host_rss_abort_fraction_of_allocation"]),
        gpu_abort_fraction=float(guard["gpu_reserved_abort_fraction_of_allocation"]),
    )


# ---------------------------------------------------------------------
# Repository ancestry / worktree-cleanliness (Finding 3 repair).
# `required_ancestor_commit` need only be an ANCESTOR of (or equal to)
# the executing `repository_commit` -- never required to be exactly
# equal, since the final benchmark implementation commit is legitimately
# a descendant of the frozen prerequisite base commit.
# ---------------------------------------------------------------------


def _run_git(repo_root: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", "-C", str(repo_root), *args], check=False,
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
    )


def collect_repository_state(repo_root: Path) -> dict[str, Any]:
    """The current ``repository_commit`` (via ``git rev-parse HEAD``)
    and ``repository_worktree_clean`` (via ``git status --porcelain``,
    which already reports untracked files by default -- no ``-uall``
    needed since that IS git's default untracked-file mode). Never
    reads a cached/stale value."""
    head = _run_git(repo_root, "rev-parse", "HEAD")
    if head.returncode != 0:
        raise DfpPhase1bChunkBenchmarkIdentityError(f"cannot determine repository_commit via 'git rev-parse HEAD': {head.stderr.strip()}")
    commit = head.stdout.strip()
    if not _HEX40.match(commit):
        raise DfpPhase1bChunkBenchmarkIdentityError(f"'git rev-parse HEAD' returned a malformed commit id: {commit!r}")

    status = _run_git(repo_root, "status", "--porcelain")
    if status.returncode != 0:
        raise DfpPhase1bChunkBenchmarkIdentityError(f"cannot determine worktree cleanliness via 'git status --porcelain': {status.stderr.strip()}")
    clean = status.stdout.strip() == ""
    return {"repository_commit": commit, "repository_worktree_clean": clean}


def require_clean_worktree(repo_root: Path) -> str:
    """Execution-time gate (Section 5): raises unless the CURRENT
    worktree is clean, including untracked files. Returns the current
    commit on success. Must be called before any torch/CUDA/model
    import."""
    state = collect_repository_state(repo_root)
    if not state["repository_worktree_clean"]:
        raise DfpPhase1bChunkBenchmarkIdentityError(
            "repository worktree is not clean (tracked modifications and/or untracked files present) -- "
            "run-trial refuses to execute against a dirty checkout"
        )
    return state["repository_commit"]


def verify_ancestor_relation(repo_root: Path, *, required_ancestor_commit: str, repository_commit: str) -> None:
    """Requires ``required_ancestor_commit`` to be an ancestor of (or
    equal to) ``repository_commit``, using Git's own commit graph --
    equivalent to ``git merge-base --is-ancestor <required> <repository_commit>``.
    Never requires exact equality. Rejects malformed hashes and
    missing commit objects with the declared domain error."""
    for label, value in (("required_ancestor_commit", required_ancestor_commit), ("repository_commit", repository_commit)):
        if not isinstance(value, str) or not _HEX40.match(value):
            raise DfpPhase1bChunkBenchmarkIdentityError(f"{label} must be a 40-hex-character commit id, observed {value!r}")

    for commit in (required_ancestor_commit, repository_commit):
        exists = _run_git(repo_root, "cat-file", "-e", f"{commit}^{{commit}}")
        if exists.returncode != 0:
            raise DfpPhase1bChunkBenchmarkIdentityError(f"commit object {commit!r} does not exist in this repository")

    result = _run_git(repo_root, "merge-base", "--is-ancestor", required_ancestor_commit, repository_commit)
    if result.returncode not in (0, 1):
        raise DfpPhase1bChunkBenchmarkIdentityError(
            f"'git merge-base --is-ancestor {required_ancestor_commit} {repository_commit}' failed unexpectedly: {result.stderr.strip()}"
        )
    if result.returncode != 0:
        raise DfpPhase1bChunkBenchmarkIdentityError(
            f"required_ancestor_commit {required_ancestor_commit!r} is not an ancestor of (nor equal to) "
            f"repository_commit {repository_commit!r} -- unrelated or reversed history"
        )


def code_binding_hashes(document: Mapping[str, Any], *, repo_root: Path) -> dict[str, str]:
    """The four benchmark-code SHA-256 values, re-read live from disk
    (never trusted from the parsed E17 document's own pinned values --
    those are what CURRENT bytes must match, not a value to echo back
    unchecked)."""
    out = {}
    name_to_field = {
        "identity_loader_module": "identity_loader_sha256", "benchmark_runner_module": "runner_sha256",
        "benchmark_cli_module": "cli_sha256", "launcher_script": "launcher_sha256",
    }
    for binding_name, field_name in name_to_field.items():
        relative_path = document["dependency_bindings"][binding_name]["relative_path"]
        target = resolve_repository_relative_path(repo_root, relative_path, binding_name=binding_name)
        out[field_name] = _sha256_of(target)
    return out


